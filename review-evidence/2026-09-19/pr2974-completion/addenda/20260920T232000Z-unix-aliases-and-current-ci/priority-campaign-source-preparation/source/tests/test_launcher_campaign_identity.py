def distribution(root: Path) -> importlib.metadata.Distribution:
    return cast(importlib.metadata.Distribution, cast(object, SimpleNamespace(locate_file=lambda name: root / name)))


def fixture(tmp_path: Path) -> tuple[Path, Path]:
    wheel = tmp_path / "source.whl"
    root = tmp_path / "installed"
    files = {
        "codex_plugin_scanner/__init__.py": b"value = 1\n",
        "codex_plugin_scanner/empty.py": b"",
        "hol_guard.dist-info/METADATA": b"Name: hol-guard\n",
        "hol_guard.dist-info/RECORD": b"original wheel RECORD\n",
    }
    with zipfile.ZipFile(wheel, "w") as archive:
        for name, body in files.items():
            archive.writestr(name, body)
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(body)
    return wheel, root


def test_original_members_include_empty_files_and_exclude_generated_cache_census(tmp_path: Path) -> None:
    wheel, root = fixture(tmp_path)
    cache = root / "codex_plugin_scanner/__pycache__/generated.pyc"
    cache.parent.mkdir()
    cache.write_bytes(b"generated bytecode is outside original-member scope")
    (root / "hol_guard.dist-info/RECORD").write_bytes(b"installed RECORD verified by separate original verifier")
    assert wheel_members(distribution(root), wheel) == 3
    assert digest(root / "codex_plugin_scanner/empty.py") == {"bytes": 0, "sha256": hashlib.sha256(b"").hexdigest()}


@pytest.mark.parametrize("kind", ["tamper", "missing", "symlink", "escaping_parent"])
def test_real_member_identity_refusals(tmp_path: Path, kind: str) -> None:
    wheel, root = fixture(tmp_path)
    original = root / "codex_plugin_scanner/__init__.py"
    if kind == "tamper":
        original.write_bytes(b"value = 2\n")
    elif kind == "missing":
        original.unlink()
    elif kind == "symlink":
        target = tmp_path / "target"
        target.write_bytes(original.read_bytes())
        original.unlink()
        original.symlink_to(target)
    else:
        moved = tmp_path / "outside"
        original.parent.rename(moved)
        original.parent.symlink_to(moved, target_is_directory=True)
    with pytest.raises((ValueError, OSError)):
        wheel_members(distribution(root), wheel)


@pytest.mark.parametrize("name", ["../escape", "/absolute"])
def test_unsafe_original_wheel_name_refuses_before_target_lookup(tmp_path: Path, name: str) -> None:
    wheel, root = fixture(tmp_path)
    with zipfile.ZipFile(wheel, "a") as archive:
        archive.writestr(name, b"unsafe")
    with pytest.raises(ValueError, match="path"):
        wheel_members(distribution(root), wheel)


def test_duplicate_original_wheel_names_refused(tmp_path: Path) -> None:
    wheel, root = fixture(tmp_path)
    with zipfile.ZipFile(wheel, "a") as archive, pytest.warns(UserWarning):
        archive.writestr("codex_plugin_scanner/empty.py", b"")
    with pytest.raises(ValueError, match="duplicate"):
        wheel_members(distribution(root), wheel)


def test_record_origin_json_duplicates_are_never_last_wins() -> None:
    with pytest.raises(ValueError, match="duplicate"):
        json.loads('{"url":"one","url":"two"}', object_pairs_hook=unique_pairs)


