def test_complete_installed_identity_calls_original_guards_twice_and_preserves_rule_domain(installed_subject) -> None:
    item = installed_subject
    assert item.subject() == item.expected
    assert item.subject() == item.expected
    assert item.observed == ["import_origin", "record", "native_status"] * 2
    assert item.subject.inventories[0] == item.subject.inventories[1]
    assert item.subject.runtime == item.status.identity.path
    assert item.expected["runtime_rule_digest"] != item.expected["policy_fixture_sha256"]
    with pytest.raises(ValueError, match="identity_call_bound"):
        item.subject()


