@pytest.mark.parametrize(
    "kind",
    ["native_unavailable", "build", "target", "provider", "expected", "package", "mode", "default", "environment"],
)
def test_installed_identity_admission_refuses_concrete_mismatch(installed_subject, kind: str) -> None:
    item = installed_subject
    if kind == "native_unavailable":
        item.status.available = False
    elif kind == "build":
        item.capabilities.build_sha = "f" * 40
    elif kind == "target":
        item.capabilities.target = "x86_64-unknown-linux-gnu"
    elif kind == "provider":
        (item.subject.providers / item.subject.contract["providers"][0]["path"]).write_bytes(b"changed")
    elif kind == "expected":
        item.expected["runtime_rule_digest"] = "f" * 64
    elif kind == "package":
        item.state["package"] = "f" * 64
    elif kind == "mode":
        item.subject.python.chmod(0o777)
    elif kind == "default":
        item.subject.contract["default_native_features"] = False
    else:
        item.state["environment"] = ["forbidden_override"]
    with pytest.raises(ValueError):
        item.subject()


